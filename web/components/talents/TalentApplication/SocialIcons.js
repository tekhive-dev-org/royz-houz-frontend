export function getSocialPlatformIcon(platformName, className = "w-5 h-5") {
  const norm = String(platformName || "").toLowerCase();
  if (norm.includes("instagram")) return <InstagramIcon className={className} />;
  if (norm.includes("tiktok")) return <TikTokIcon className={className} />;
  if (norm.includes("twitter") || norm === "x" || norm.includes("x /")) return <XTwitterIcon className={className} />;
  if (norm.includes("youtube")) return <YouTubeIcon className={className} />;
  if (norm.includes("facebook")) return <FacebookIcon className={className} />;
  if (norm.includes("whatsapp")) return <WhatsAppIcon className={className} />;
  if (norm.includes("github")) return <GitHubIcon className={className} />;
  if (norm.includes("linkedin")) return <LinkedInIcon className={className} />;
  if (norm.includes("pinterest")) return <PinterestIcon className={className} />;
  return <OthersIcon className={className} />;
}
